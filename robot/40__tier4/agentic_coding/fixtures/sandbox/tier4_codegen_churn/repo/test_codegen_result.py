"""Visible test: the generated module must exist and expose VERSION.

This is the committed red baseline: codegen_result.py is absent in the seed, so
the import fails at t=0 and passes once the agent generates the module.
"""

import unittest


class TestCodegenResult(unittest.TestCase):
    def test_generated_module_exposes_version(self):
        import codegen_result  # generated by the agent; absent in the seed

        self.assertEqual(codegen_result.VERSION, "1.0.0")


if __name__ == "__main__":
    unittest.main()
